<?php

namespace OPNsense\AppIdentification\Backend;

class BackendResult
{
    public static function ok(array $data = [], string $message = 'ok'): array
    {
        return array_merge(['status' => 'ok', 'message' => $message], $data);
    }

    public static function error(string $message, array $data = []): array
    {
        return array_merge(['status' => 'error', 'message' => $message], $data);
    }
}

class CapabilityProbe
{
    public function probe(array $settings = []): array
    {
        $items = [
            'ntopng_binary' => $this->command('ntopng') || is_executable('/usr/local/bin/ntopng'),
            'ntopng_rc' => is_executable('/usr/local/etc/rc.d/ntopng'),
            'redis_binary' => $this->command('redis-server') || is_executable('/usr/local/bin/redis-server'),
            'redis_rc' => is_executable('/usr/local/etc/rc.d/redis'),
            'config_dir_writable' => $this->dirWritable('/usr/local/etc/ntopng'),
            'rules_dir_writable' => $this->dirWritable('/var/lib/ntopng'),
        ];
        if (!empty($settings)) {
            $client = new NtopngClient($settings);
            $items['ntopng_api'] = ($client->get('flow/active.lua', ['ifid' => $settings['ifid'] ?? 0, 'perPage' => 1])['status'] ?? '') !== 'error';
        }
        return [
            'available' => $items,
            'missing' => array_keys(array_filter($items, static fn($ok) => !$ok)),
        ];
    }

    private function command(string $command): bool
    {
        return trim((string)shell_exec('command -v ' . escapeshellarg($command) . ' 2>/dev/null')) !== '';
    }

    private function dirWritable(string $path): bool
    {
        return is_dir($path) ? is_writable($path) : is_writable(dirname($path));
    }
}

class ConflictDetector
{
    public function detect(): array
    {
        $conflicts = [];
        foreach (['os-ntopng', 'os-redis'] as $pkg) {
            exec('/usr/local/sbin/pkg info -e ' . escapeshellarg($pkg) . ' 2>/dev/null', $out, $code);
            if ($code === 0) {
                $conflicts[] = ['type' => 'plugin', 'name' => $pkg, 'message' => "{$pkg} is installed; App Identification will not overwrite external plugin state."];
            }
        }
        return $conflicts;
    }
}

class ConfigManager
{
    private const TARGET_DIR = '/usr/local/etc/ntopng';
    private const TARGET_FILE = '/usr/local/etc/ntopng/ntopng.conf';

    public function generate(array $config): array
    {
        if (!is_dir(self::TARGET_DIR) && !mkdir(self::TARGET_DIR, 0755, true)) {
            return BackendResult::error('failed to create ' . self::TARGET_DIR);
        }
        $lines = [
            '# Autogenerated by os-app-identification',
            '# Do not edit manually',
            '',
        ];
        if (($config['enabled'] ?? '0') === '1') {
            $lines[] = '-e=';
        }
        foreach (explode(',', (string)($config['interfaces'] ?? '')) as $iface) {
            $iface = trim($iface);
            if ($iface !== '') {
                $lines[] = '-i=' . $iface;
            }
        }
        foreach ([
            '--http-port' => $config['http_port'] ?? '3000',
            '--https-port' => $config['https_port'] ?? '',
            '--dns-mode' => $config['dns_mode'] ?? '0',
            '--https-cert' => $config['certificate'] ?? '',
            '--max-num-flows' => $config['max_flows'] ?? '200000',
            '--max-num-hosts' => $config['max_hosts'] ?? '100000',
            '--local-networks' => $config['local_networks'] ?? '',
        ] as $key => $value) {
            if ((string)$value !== '') {
                $lines[] = $key . '=' . $value;
            }
        }
        foreach (preg_split('/[;\r\n]+/', (string)($config['extra_options'] ?? '')) as $option) {
            $option = trim($option);
            if ($option !== '') {
                $lines[] = $option;
            }
        }
        if (file_put_contents(self::TARGET_FILE, implode("\n", $lines) . "\n") === false) {
            return BackendResult::error('failed to write ' . self::TARGET_FILE);
        }
        return BackendResult::ok(['data' => ['generated' => self::TARGET_FILE]], 'ntopng.conf generated');
    }
}

class ServiceManager
{
    public function restart(): array
    {
        exec('/usr/local/etc/rc.d/ntopng restart 2>&1', $output, $code);
        return $code === 0 ? BackendResult::ok(['data' => ['method' => 'restart']], 'ntopng restarted') : BackendResult::error(trim(implode("\n", $output)) ?: 'failed to restart ntopng');
    }

    public function reload(): array
    {
        exec('/bin/pgrep -x ntopng 2>/dev/null', $pids, $pgrepCode);
        if ($pgrepCode === 0) {
            exec('/usr/bin/pkill -HUP -x ntopng 2>&1', $output, $code);
            if ($code === 0) {
                return BackendResult::ok(['data' => ['method' => 'sighup']], 'ntopng reloaded');
            }
        }
        return $this->restart();
    }

    public function status(): array
    {
        exec('/bin/pgrep -x ntopng 2>/dev/null', $pids);
        $pids = array_values(array_filter(array_map('intval', $pids)));
        return BackendResult::ok(['data' => ['running' => count($pids) > 0, 'pids' => $pids]], count($pids) > 0 ? 'ntopng running' : 'ntopng stopped');
    }
}

class RuleStore
{
    private const RULES_FILE = '/var/lib/ntopng/protos.txt';
    private const RULES_BAK = '/var/lib/ntopng/protos.txt.bak';

    public function read(): array
    {
        $rules = [];
        if (is_file(self::RULES_FILE)) {
            foreach (file(self::RULES_FILE, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
                $line = trim((string)$line);
                if ($line !== '') {
                    $rules[] = $line;
                }
            }
        }
        return BackendResult::ok(['data' => $rules, 'file' => self::RULES_FILE], 'rules read');
    }

    public function write(array $rules): array
    {
        $dir = dirname(self::RULES_FILE);
        if (!is_dir($dir) && !mkdir($dir, 0755, true)) {
            return BackendResult::error('failed to create ' . $dir);
        }
        $lines = [];
        foreach ($rules as $rule) {
            if (is_scalar($rule)) {
                $line = trim((string)$rule);
                if ($line !== '') {
                    $lines[] = $line;
                }
            }
        }
        if (is_file(self::RULES_FILE)) {
            @copy(self::RULES_FILE, self::RULES_BAK);
        }
        if (file_put_contents(self::RULES_FILE, implode("\n", $lines) . (empty($lines) ? '' : "\n")) === false) {
            return BackendResult::error('failed to write ' . self::RULES_FILE);
        }
        @chown(self::RULES_FILE, 'ntopng');
        @chgrp(self::RULES_FILE, 'ntopng');
        @chmod(self::RULES_FILE, 0640);
        return BackendResult::ok(['data' => ['written' => count($lines), 'file' => self::RULES_FILE, 'backup' => self::RULES_BAK]], 'rules written');
    }
}

class NtopngClient
{
    private array $settings;

    public function __construct(array $settings)
    {
        $this->settings = $settings;
    }

    public function get(string $endpoint, array $params = []): array
    {
        $endpoint = ltrim($endpoint, '/');
        $url = $this->baseUrl() . $endpoint;
        if (!empty($params)) {
            $url .= (strpos($url, '?') === false ? '?' : '&') . http_build_query($params);
        }
        $headers = ['Accept: application/json'];
        $token = trim((string)($this->settings['auth_token'] ?? ''));
        $cookie = '';
        if ($token !== '') {
            $headers[] = 'Authorization: Token ' . $token;
        } else {
            $cookie = $this->sessionCookie();
            if ($cookie === '') {
                return BackendResult::error('ntopng authentication failed');
            }
        }
        $ch = curl_init($url);
        if ($ch === false) {
            return BackendResult::error('unable to initialize cURL client');
        }
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_CONNECTTIMEOUT => 5,
            CURLOPT_TIMEOUT => 5,
            CURLOPT_FAILONERROR => false,
            CURLOPT_FOLLOWLOCATION => false,
            CURLOPT_HTTPHEADER => $headers,
        ]);
        if ($cookie !== '') {
            curl_setopt($ch, CURLOPT_COOKIE, $cookie);
        }
        $body = curl_exec($ch);
        $httpCode = (int)curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $curlErr = curl_error($ch);
        curl_close($ch);
        if ($body === false || $httpCode === 0) {
            return BackendResult::error($curlErr !== '' ? $curlErr : 'unable to connect to ntopng', ['http_code' => $httpCode]);
        }
        if ($httpCode === 302) {
            return BackendResult::error('ntopng authentication failed', ['http_code' => $httpCode]);
        }
        if ($httpCode >= 400) {
            return BackendResult::error("ntopng returned HTTP error {$httpCode}", ['http_code' => $httpCode]);
        }
        $decoded = json_decode((string)$body, true);
        if (!is_array($decoded)) {
            return BackendResult::error('invalid JSON returned by ntopng', ['http_code' => $httpCode]);
        }
        return $decoded;
    }

    private function baseUrl(): string
    {
        return sprintf('%s://%s:%s/lua/rest/v2/get/', $this->scheme(), $this->host(), $this->port());
    }

    private function sessionCookie(): string
    {
        $user = trim((string)($this->settings['auth_username'] ?? 'admin'));
        $pass = (string)($this->settings['auth_password'] ?? '');
        if ($user === '' || $pass === '') {
            return '';
        }
        $port = $this->port();
        $ch = curl_init(sprintf('%s://%s:%s/authorize.html', $this->scheme(), $this->host(), $port));
        if ($ch === false) {
            return '';
        }
        curl_setopt_array($ch, [
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => http_build_query(['user' => $user, 'password' => $pass]),
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_HEADER => true,
            CURLOPT_FOLLOWLOCATION => false,
            CURLOPT_TIMEOUT => 5,
        ]);
        $response = curl_exec($ch);
        curl_close($ch);
        if (!is_string($response) || strpos($response, 'wrong-credentials') !== false) {
            return '';
        }
        preg_match('/Set-Cookie:\s*(session_' . preg_quote($port, '/') . '_\d+=[^;]+)/i', $response, $matches);
        return $matches[1] ?? '';
    }

    private function scheme(): string
    {
        return strtolower((string)($this->settings['rest_scheme'] ?? 'http')) === 'https' ? 'https' : 'http';
    }

    private function host(): string
    {
        $host = trim((string)($this->settings['rest_host'] ?? '127.0.0.1'));
        return $host !== '' ? $host : '127.0.0.1';
    }

    private function port(): string
    {
        $port = trim((string)($this->settings['rest_port'] ?? '3000'));
        return $port !== '' && is_numeric($port) ? $port : '3000';
    }
}

class BackendCore
{
    public function dispatch(array $request): array
    {
        try {
            $action = (string)($request['action'] ?? 'status');
            $settings = is_array($request['settings'] ?? null) ? $request['settings'] : [];
            switch ($action) {
                case 'capabilities':
                    return BackendResult::ok(['capabilities' => (new CapabilityProbe())->probe($settings), 'conflicts' => (new ConflictDetector())->detect()]);
                case 'status':
                    $status = (new ServiceManager())->status();
                    $status['capabilities'] = (new CapabilityProbe())->probe($settings);
                    $status['conflicts'] = (new ConflictDetector())->detect();
                    return $status;
                case 'generate':
                    return (new ConfigManager())->generate(is_array($request['config'] ?? null) ? $request['config'] : []);
                case 'restart':
                    return (new ServiceManager())->restart();
                case 'reload':
                    return (new ServiceManager())->reload();
                case 'read_rules':
                    return (new RuleStore())->read();
                case 'write_rules':
                    return (new RuleStore())->write(is_array($request['rules'] ?? null) ? $request['rules'] : []);
                case 'api_get':
                    return (new NtopngClient($settings))->get((string)($request['endpoint'] ?? ''), is_array($request['params'] ?? null) ? $request['params'] : []);
                default:
                    return BackendResult::error('unsupported action');
            }
        } catch (\Throwable $e) {
            return BackendResult::error($e->getMessage());
        }
    }
}
