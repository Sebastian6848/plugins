<?php

namespace OPNsense\AppIdentification\Backend;

class BackendResult
{
    public static function ok(array $data = [], string $message = 'ok'): array
    {
        return array_merge(['status' => 'ok', 'message' => $message], $data);
    }

    public static function error(string $message, array $data = []): array
    {
        return array_merge(['status' => 'error', 'message' => $message], $data);
    }
}

class CapabilityProbe
{
    public function probe(array $settings = []): array
    {
        $items = [
            'ntopng_binary' => $this->command('ntopng') || is_executable('/usr/local/bin/ntopng'),
            'ntopng_rc' => is_executable('/usr/local/etc/rc.d/ntopng'),
            'redis_binary' => $this->command('redis-server') || is_executable('/usr/local/bin/redis-server'),
            'redis_rc' => is_executable('/usr/local/etc/rc.d/redis'),
            'ntopng_config_writable' => $this->pathWritable('/usr/local/etc/ntopng.conf'),
            'redis_config_writable' => $this->pathWritable('/usr/local/etc/redis.conf'),
            'rc_conf_dir_writable' => $this->dirWritable('/etc/rc.conf.d'),
            'rules_dir_writable' => $this->dirWritable('/var/db/ntopng'),
        ];
        if (!empty($settings)) {
            $client = new NtopngClient($settings);
            $items['ntopng_api'] = ($client->get('flow/active.lua', ['ifid' => $settings['ifid'] ?? 0, 'perPage' => 1])['status'] ?? '') !== 'error';
        }
        return [
            'available' => $items,
            'missing' => array_keys(array_filter($items, static fn($ok) => !$ok)),
        ];
    }

    private function command(string $command): bool
    {
        return trim((string)shell_exec('command -v ' . escapeshellarg($command) . ' 2>/dev/null')) !== '';
    }

    private function dirWritable(string $path): bool
    {
        return is_dir($path) ? is_writable($path) : is_writable(dirname($path));
    }

    private function pathWritable(string $path): bool
    {
        return is_file($path) ? is_writable($path) : is_writable(dirname($path));
    }
}

class ConflictDetector
{
    public function detect(): array
    {
        $conflicts = [];
        foreach (['os-ntopng', 'os-redis'] as $pkg) {
            exec('/usr/local/sbin/pkg info -e ' . escapeshellarg($pkg) . ' 2>/dev/null', $out, $code);
            if ($code === 0) {
                $conflicts[] = ['type' => 'plugin', 'name' => $pkg, 'message' => "{$pkg} is installed; App Identification will not overwrite external plugin state."];
            }
        }
        return $conflicts;
    }
}

class ConfigManager
{
    private const NTOPNG_CONFIG = '/usr/local/etc/ntopng.conf';
    private const NTOPNG_RC = '/etc/rc.conf.d/ntopng';
    private const REDIS_CONFIG = '/usr/local/etc/redis.conf';
    private const REDIS_RC = '/etc/rc.conf.d/redis';

    public function generate(array $config): array
    {
        $conflicts = (new ConflictDetector())->detect();
        foreach ($conflicts as $conflict) {
            if (in_array($conflict['name'] ?? '', ['os-ntopng', 'os-redis'], true)) {
                return BackendResult::error(
                    'legacy service plugin installed; refusing to overwrite ntopng/redis managed configuration',
                    ['conflicts' => $conflicts]
                );
            }
        }

        $runtime = (new RuntimePreparer())->prepare();
        if (($runtime['status'] ?? '') === 'error') {
            return $runtime;
        }

        foreach ([dirname(self::NTOPNG_RC), dirname(self::REDIS_RC)] as $dir) {
            if (!is_dir($dir) && !mkdir($dir, 0755, true)) {
                return BackendResult::error('failed to create ' . $dir);
            }
        }

        $redis = $this->generateRedis();
        if (($redis['status'] ?? '') === 'error') {
            return $redis;
        }

        $ntopng = $this->generateNtopng($config);
        if (($ntopng['status'] ?? '') === 'error') {
            return $ntopng;
        }

        return BackendResult::ok([
            'data' => [
                'generated' => [
                    self::REDIS_CONFIG,
                    self::REDIS_RC,
                    self::NTOPNG_CONFIG,
                    self::NTOPNG_RC,
                ],
            ],
        ], 'redis and ntopng configuration generated');
    }

    private function generateNtopng(array $config): array
    {
        $enabled = ($config['enabled'] ?? '0') === '1';
        $lines = $enabled ? [
            '# Autogenerated by os-app-identification',
            '# Do not edit manually',
            '',
            '-d=/var/db/ntopng',
            '-r=127.0.0.1:6379',
        ] : [];

        foreach (explode(',', (string)($config['interfaces'] ?? '')) as $iface) {
            $iface = trim($iface);
            if ($iface !== '') {
                $lines[] = '-i=' . $iface;
            }
        }
        foreach ([
            '-w' => $config['http_port'] ?? '3000',
            '-W' => $config['https_port'] ?? '',
            '-n' => $config['dns_mode'] ?? '0',
            '--max-num-flows' => $config['max_flows'] ?? '200000',
            '--max-num-hosts' => $config['max_hosts'] ?? '100000',
            '--local-networks' => $config['local_networks'] ?? '',
        ] as $key => $value) {
            if ((string)$value !== '') {
                $lines[] = $key . '=' . $value;
            }
        }
        foreach (preg_split('/[;\r\n]+/', (string)($config['extra_options'] ?? '')) as $option) {
            $option = trim($option);
            if ($option !== '') {
                $lines[] = $option;
            }
        }
        if (file_put_contents(self::NTOPNG_CONFIG, implode("\n", $lines) . "\n") === false) {
            return BackendResult::error('failed to write ' . self::NTOPNG_CONFIG);
        }

        $rc = $enabled
            ? "ntopng_enable=\"YES\"\nntopng_flags=\"" . self::NTOPNG_CONFIG . "\"\n"
            : "ntopng_enable=\"NO\"\n";
        if (file_put_contents(self::NTOPNG_RC, $rc) === false) {
            return BackendResult::error('failed to write ' . self::NTOPNG_RC);
        }

        return BackendResult::ok(['data' => ['generated' => self::NTOPNG_CONFIG]], 'ntopng.conf generated');
    }

    private function generateRedis(): array
    {
        $config = <<<CONF
# Autogenerated by os-app-identification
# Do not edit manually
bind 127.0.0.1 ::1
protected-mode yes
port 6379
unixsocket /var/run/redis/redis.sock
unixsocketperm 700
timeout 0
tcp-keepalive 300
daemonize yes
supervised no
pidfile /var/run/redis/redis.pid
loglevel notice
logfile /var/log/redis/redis.log
databases 16
dir /var/db/redis
appendonly no

CONF;
        if (file_put_contents(self::REDIS_CONFIG, $config) === false) {
            return BackendResult::error('failed to write ' . self::REDIS_CONFIG);
        }
        if (file_put_contents(self::REDIS_RC, "redis_enable=\"YES\"\n") === false) {
            return BackendResult::error('failed to write ' . self::REDIS_RC);
        }
        return BackendResult::ok(['data' => ['generated' => self::REDIS_CONFIG]], 'redis.conf generated');
    }
}

class RuntimePreparer
{
    public function prepare(): array
    {
        foreach ([
            '/var/run/ntopng' => ['ntopng', 'ntopng', 0755],
            '/var/db/ntopng' => ['ntopng', 'wheel', 0755],
            '/var/db/redis' => ['redis', 'redis', 0755],
            '/var/log/redis' => ['redis', 'redis', 0755],
            '/var/run/redis' => ['redis', 'redis', 0755],
        ] as $dir => $meta) {
            if (!is_dir($dir) && !mkdir($dir, $meta[2], true)) {
                return BackendResult::error('failed to create ' . $dir);
            }
            @chown($dir, $meta[0]);
            @chgrp($dir, $meta[1]);
            @chmod($dir, $meta[2]);
        }
        if (!is_file('/var/log/redis/redis.log')) {
            @touch('/var/log/redis/redis.log');
        }
        @chown('/var/log/redis/redis.log', 'redis');
        @chgrp('/var/log/redis/redis.log', 'redis');
        return BackendResult::ok([], 'runtime directories prepared');
    }
}

class ServiceManager
{
    public function start(): array
    {
        $runtime = (new RuntimePreparer())->prepare();
        if (($runtime['status'] ?? '') === 'error') {
            return $runtime;
        }

        $redis = $this->runRc('redis', 'onestart');
        if (($redis['status'] ?? '') === 'error' && !$this->isRunning('redis-server')) {
            return $redis;
        }

        $ntopng = $this->runRc('ntopng', 'onestart');
        if (($ntopng['status'] ?? '') === 'error' && !$this->isRunning('ntopng')) {
            return $ntopng;
        }

        return BackendResult::ok(['components' => $this->components()], 'redis and ntopng started');
    }

    public function stop(): array
    {
        $ntopng = $this->runRc('ntopng', 'onestop');
        if (($ntopng['status'] ?? '') === 'error' && $this->isRunning('ntopng')) {
            return $ntopng;
        }
        return BackendResult::ok(['components' => $this->components()], 'ntopng stopped');
    }

    public function restart(): array
    {
        $runtime = (new RuntimePreparer())->prepare();
        if (($runtime['status'] ?? '') === 'error') {
            return $runtime;
        }

        $redis = $this->runRc('redis', 'onestart');
        if (($redis['status'] ?? '') === 'error' && !$this->isRunning('redis-server')) {
            return $redis;
        }

        $ntopng = $this->runRc('ntopng', 'onerestart');
        if (($ntopng['status'] ?? '') === 'error') {
            $ntopng = $this->runRc('ntopng', 'onestart');
        }
        return ($ntopng['status'] ?? '') === 'error'
            ? $ntopng
            : BackendResult::ok(['components' => $this->components(), 'data' => ['method' => 'restart']], 'redis started and ntopng restarted');
    }

    public function reload(): array
    {
        exec('/bin/pgrep -x ntopng 2>/dev/null', $pids, $pgrepCode);
        if ($pgrepCode === 0) {
            exec('/usr/bin/pkill -HUP -x ntopng 2>&1', $output, $code);
            if ($code === 0) {
                return BackendResult::ok(['data' => ['method' => 'sighup']], 'ntopng reloaded');
            }
        }
        return $this->restart();
    }

    public function status(): array
    {
        $components = $this->components();
        $ntopngRunning = $components['ntopng']['running'];
        $redisRunning = $components['redis']['running'];
        $status = $ntopngRunning && $redisRunning ? 'running' : ($ntopngRunning || $redisRunning ? 'degraded' : 'stopped');
        return BackendResult::ok(
            [
                'service_status' => $status,
                'components' => $components,
                'data' => ['running' => $ntopngRunning, 'pids' => $components['ntopng']['pids']],
            ],
            $status === 'running' ? 'ntopng and redis running' : 'ntopng/redis not fully running'
        );
    }

    private function components(): array
    {
        return [
            'redis' => [
                'running' => $this->isRunning('redis-server'),
                'pids' => $this->pids('redis-server'),
            ],
            'ntopng' => [
                'running' => $this->isRunning('ntopng'),
                'pids' => $this->pids('ntopng'),
            ],
        ];
    }

    private function runRc(string $service, string $action): array
    {
        $script = '/usr/local/etc/rc.d/' . $service;
        if (!is_executable($script)) {
            return BackendResult::error($service . ' rc script is missing');
        }
        exec($script . ' ' . escapeshellarg($action) . ' 2>&1', $output, $code);
        return $code === 0
            ? BackendResult::ok(['data' => ['service' => $service, 'action' => $action]], $service . ' ' . $action . ' ok')
            : BackendResult::error(trim(implode("\n", $output)) ?: 'failed to run ' . $service . ' ' . $action);
    }

    private function isRunning(string $process): bool
    {
        return count($this->pids($process)) > 0;
    }

    private function pids(string $process): array
    {
        exec('/bin/pgrep -x ' . escapeshellarg($process) . ' 2>/dev/null', $pids);
        return array_values(array_filter(array_map('intval', $pids)));
    }
}

class RuleStore
{
    private const RULES_FILE = '/var/db/ntopng/protos.txt';
    private const RULES_BAK = '/var/db/ntopng/protos.txt.bak';

    public function read(): array
    {
        $rules = [];
        if (is_file(self::RULES_FILE)) {
            foreach (file(self::RULES_FILE, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
                $line = trim((string)$line);
                if ($line !== '') {
                    $rules[] = $line;
                }
            }
        }
        return BackendResult::ok(['data' => $rules, 'file' => self::RULES_FILE], 'rules read');
    }

    public function write(array $rules): array
    {
        $dir = dirname(self::RULES_FILE);
        if (!is_dir($dir) && !mkdir($dir, 0755, true)) {
            return BackendResult::error('failed to create ' . $dir);
        }
        $lines = [];
        foreach ($rules as $rule) {
            if (is_scalar($rule)) {
                $line = trim((string)$rule);
                if ($line !== '') {
                    $lines[] = $line;
                }
            }
        }
        if (is_file(self::RULES_FILE)) {
            @copy(self::RULES_FILE, self::RULES_BAK);
        }
        if (file_put_contents(self::RULES_FILE, implode("\n", $lines) . (empty($lines) ? '' : "\n")) === false) {
            return BackendResult::error('failed to write ' . self::RULES_FILE);
        }
        @chown(self::RULES_FILE, 'ntopng');
        @chgrp(self::RULES_FILE, 'ntopng');
        @chmod(self::RULES_FILE, 0640);
        return BackendResult::ok(['data' => ['written' => count($lines), 'file' => self::RULES_FILE, 'backup' => self::RULES_BAK]], 'rules written');
    }
}

class NtopngClient
{
    private array $settings;

    public function __construct(array $settings)
    {
        $this->settings = $settings;
    }

    public function get(string $endpoint, array $params = []): array
    {
        $endpoint = ltrim($endpoint, '/');
        $url = $this->baseUrl() . $endpoint;
        if (!empty($params)) {
            $url .= (strpos($url, '?') === false ? '?' : '&') . http_build_query($params);
        }
        $headers = ['Accept: application/json'];
        $token = trim((string)($this->settings['auth_token'] ?? ''));
        $cookie = '';
        if ($token !== '') {
            $headers[] = 'Authorization: Token ' . $token;
        } else {
            $cookie = $this->sessionCookie();
            if ($cookie === '') {
                return BackendResult::error('ntopng authentication failed');
            }
        }
        $ch = curl_init($url);
        if ($ch === false) {
            return BackendResult::error('unable to initialize cURL client');
        }
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_CONNECTTIMEOUT => 5,
            CURLOPT_TIMEOUT => 5,
            CURLOPT_FAILONERROR => false,
            CURLOPT_FOLLOWLOCATION => false,
            CURLOPT_HTTPHEADER => $headers,
        ]);
        if ($cookie !== '') {
            curl_setopt($ch, CURLOPT_COOKIE, $cookie);
        }
        $body = curl_exec($ch);
        $httpCode = (int)curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $curlErr = curl_error($ch);
        curl_close($ch);
        if ($body === false || $httpCode === 0) {
            return BackendResult::error($curlErr !== '' ? $curlErr : 'unable to connect to ntopng', ['http_code' => $httpCode]);
        }
        if ($httpCode === 302) {
            return BackendResult::error('ntopng authentication failed', ['http_code' => $httpCode]);
        }
        if ($httpCode >= 400) {
            return BackendResult::error("ntopng returned HTTP error {$httpCode}", ['http_code' => $httpCode]);
        }
        $decoded = json_decode((string)$body, true);
        if (!is_array($decoded)) {
            return BackendResult::error('invalid JSON returned by ntopng', ['http_code' => $httpCode]);
        }
        return $decoded;
    }

    private function baseUrl(): string
    {
        return sprintf('%s://%s:%s/lua/rest/v2/get/', $this->scheme(), $this->host(), $this->port());
    }

    private function sessionCookie(): string
    {
        $user = trim((string)($this->settings['auth_username'] ?? 'admin'));
        $pass = (string)($this->settings['auth_password'] ?? '');
        if ($user === '' || $pass === '') {
            return '';
        }
        $port = $this->port();
        $ch = curl_init(sprintf('%s://%s:%s/authorize.html', $this->scheme(), $this->host(), $port));
        if ($ch === false) {
            return '';
        }
        curl_setopt_array($ch, [
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => http_build_query(['user' => $user, 'password' => $pass]),
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_HEADER => true,
            CURLOPT_FOLLOWLOCATION => false,
            CURLOPT_TIMEOUT => 5,
        ]);
        $response = curl_exec($ch);
        curl_close($ch);
        if (!is_string($response) || strpos($response, 'wrong-credentials') !== false) {
            return '';
        }
        preg_match('/Set-Cookie:\s*(session_' . preg_quote($port, '/') . '_\d+=[^;]+)/i', $response, $matches);
        return $matches[1] ?? '';
    }

    private function scheme(): string
    {
        return strtolower((string)($this->settings['rest_scheme'] ?? 'http')) === 'https' ? 'https' : 'http';
    }

    private function host(): string
    {
        $host = trim((string)($this->settings['rest_host'] ?? '127.0.0.1'));
        return $host !== '' ? $host : '127.0.0.1';
    }

    private function port(): string
    {
        $port = trim((string)($this->settings['rest_port'] ?? '3000'));
        return $port !== '' && is_numeric($port) ? $port : '3000';
    }
}

class BackendCore
{
    public function dispatch(array $request): array
    {
        try {
            $action = (string)($request['action'] ?? 'status');
            $settings = is_array($request['settings'] ?? null) ? $request['settings'] : [];
            switch ($action) {
                case 'capabilities':
                    return BackendResult::ok(['capabilities' => (new CapabilityProbe())->probe($settings), 'conflicts' => (new ConflictDetector())->detect()]);
                case 'status':
                    $status = (new ServiceManager())->status();
                    $status['capabilities'] = (new CapabilityProbe())->probe($settings);
                    $status['conflicts'] = (new ConflictDetector())->detect();
                    return $status;
                case 'generate':
                    return (new ConfigManager())->generate(is_array($request['config'] ?? null) ? $request['config'] : []);
                case 'start':
                    return (new ServiceManager())->start();
                case 'stop':
                    return (new ServiceManager())->stop();
                case 'restart':
                    return (new ServiceManager())->restart();
                case 'reload':
                    return (new ServiceManager())->reload();
                case 'read_rules':
                    return (new RuleStore())->read();
                case 'write_rules':
                    return (new RuleStore())->write(is_array($request['rules'] ?? null) ? $request['rules'] : []);
                case 'api_get':
                    return (new NtopngClient($settings))->get((string)($request['endpoint'] ?? ''), is_array($request['params'] ?? null) ? $request['params'] : []);
                default:
                    return BackendResult::error('unsupported action');
            }
        } catch (\Throwable $e) {
            return BackendResult::error($e->getMessage());
        }
    }
}
